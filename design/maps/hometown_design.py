"""HomeTown: the hamlet in the Meduxnekeag hills (milestone 16). Writes design/maps/HomeTown_0.txt.

Run:  python design/maps/hometown_design.py
      python dev/mapgen.py build design/maps/HomeTown_0.txt --fresh [--apply]

Built from the corridor plan's underlay (design/region/corridor.toml: 34x28, an inset of the
start valley; `dev/corridor.py underlay "HomeTown"`). The geography, as the plan has it:
  * the border hills close the west and the north (Maine is past the trees);
  * the Meduxnekeag comes down out of the hills from the north-west as a brook, opens into the
    mill pond, and runs east along the valley floor into Route 201 (the seam: rows 16-19);
  * the road leaves east on the brook's south bank (the seam: rows 24-25).
The hamlet:
  * the player's house and the Leblancs' on the lawns of the south-west bank, their gardens,
    the lane down to the road;
  * the sawmill on the bench above the far bank, its yard, the footbridge over the outflow; a
    ledge drops from the yard to the pond shore;
  * the researcher waits where the road leaves the hamlet (the exit gate: scripts.pory).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.project import Project
from mapkit.sketch import Sketch
from mapkit.geo import Plan
from mapkit import landscape as ls, stamps

W, H = 34, 28
p = Project()
cat = stamps.catalog(p)
under = Plan().underlay("HomeTown")
assert (len(under[0]), len(under)) == (W, H), "the plan's size changed"
sk = Sketch("HomeTown_0", ["." * W for _ in range(H)], [
    "// HomeTown - the hamlet in the Meduxnekeag hills (generated by design/maps/hometown_design.py)",
    "// legend: . grass  = path  ~ brook  T forest  * flowers  b boulder  y sapling  s sign"
    "  r rock  H bridge  B building  v ledge  # keep"])

# --- the brook: down from the hills, the mill pond, east to Route 201 -------------------------
# per column (x: top row, bottom row) where it runs east-west; per row band where it comes down
BROOK_DOWN = [(8, 10, 0, 1), (9, 11, 2, 3), (10, 12, 4, 5), (11, 13, 6, 7), (12, 14, 8, 8)]
POND_COLS = {13: (8, 10), 14: (8, 11), 15: (9, 12), 16: (9, 13), 17: (9, 13), 18: (8, 13),
             19: (8, 13), 20: (9, 13), 21: (10, 14), 22: (11, 14), 23: (12, 16),
             24: (13, 16), 25: (13, 16), 26: (14, 17),
             27: (15, 18), 28: (15, 18), 29: (15, 18), 30: (15, 18),   # the footbridge: 28-29
             31: (15, 18), 32: (16, 19), 33: (16, 19)}                 # the seam (plan: 16-19)
WATER = set()
for x0, x1, t, b in BROOK_DOWN:
    WATER |= ls.rect(x0, t, x1, b)
for x, (t, b) in POND_COLS.items():
    WATER |= ls.rect(x, t, x, b)
ROCKS = ls.rect(18, 10, 19, 11)                      # a boulder in the mill pond
BRIDGE = ls.rect(28, 15, 29, 18)

# --- the road and the lanes -------------------------------------------------------------------
# The road starts at the hamlet's lanes and leaves east on the brook's south bank, stepping down
# the valley floor to the seam (rows 24-25). The mill lane crosses the footbridge.
ROAD = (ls.rect(8, 21, 21, 22) | ls.rect(20, 22, 23, 23) | ls.rect(22, 23, 26, 24)
        | ls.rect(25, 24, W - 1, 25))
MILL_LANE = ls.rect(28, 20, 29, 23)                  # from the road up to the bridge's south end
YARD_LANE = ls.rect(28, 10, 29, 13)                  # from the bridge's north end to the mill's door

# --- buildings: (stamp, top-left, room) ---------------------------------------------------------
# The two houses keep their rooms (warps 0 and 1); the sawmill is new.
BUILDINGS = [
    ("house_two_storey", (6, 9), "LittlerootTown_MyHouse_1F_0"),     # door (9,13), mat (9,14)
    ("house_two_storey_left", (14, 15), "HomeTown_House2_1F"),        # door (15,19), mat (15,20)
    ("house_wide", (26, 5), "HomeTown_Sawmill"),                      # door (28,9)
]
FOOT, STUBS = set(), set()
PATHS0 = ROAD | MILL_LANE | YARD_LANE
for name, (x, y), room in BUILDINGS:
    dx, fy = sk.place(p, name, x, y, room)
    FOOT |= cat[name].footprint(x, y)
    fy += 1
    while (dx, fy) in FOOT:
        fy += 1
    while (dx, fy) not in PATHS0 and fy < H:
        STUBS.add((dx, fy))
        fy += 1
PATHS = (PATHS0 | STUBS) - FOOT

for (x, y) in WATER - ROCKS:
    sk.set(x, y, "~")
for (x, y) in ROCKS:
    sk.set(x, y, "r")
for (x, y) in BRIDGE:
    sk.set(x, y, "H")
for (x, y) in PATHS - BRIDGE:
    sk.set(x, y, "=")

# --- a ledge: the mill's bench drops to the pond shore (one way; walk round its west end) -----
LEDGE = ls.rect(22, 8, 25, 8)
for (x, y) in LEDGE:
    sk.set(x, y, "v")

# --- woods: the hills close the west and the north; a wooded slope south of the road ---------
ALL = ls.rect(0, 0, W - 1, H - 1)
OPEN = (ls.rect(3, 4, 12, 24) | ls.rect(12, 9, 27, 24) | ls.rect(19, 3, 31, 14)
        | ls.rect(24, 15, 33, 26))
OPEN -= ls.forest_edge(0, 0, 7, 27, "E", amp=4, seed=1601)           # the border hills
OPEN -= ls.forest_edge(14, 0, 33, 4, "S", amp=2, seed=1602)           # the ridge behind the mill
OPEN -= ls.forest_edge(0, 23, 24, H - 1, "N", amp=2, seed=1603)       # the slope south of the road
# yard trees: a pair on the player's lawn, the Leblancs' shade tree, a clump by the lane's foot,
# and a grove on the mill's bench
GROVES = (ls.rect(11, 16, 12, 17) | ls.rect(22, 20, 25, 21) | ls.rect(4, 18, 5, 21)
          | ls.blob(17, 6, 1.6, 1.4, seed=1605))
OPEN -= GROVES
OPEN |= PATHS | ls.around(BRIDGE, 1)

RING = ls.around(FOOT, 1) - FOOT
CLEAR = (ls.around(PATHS, 1) | RING | FOOT | ls.around(WATER, 1) | ls.around(BRIDGE, 1)
         | ls.ledge_clearance(sk))
land = ALL - WATER
woods = land - OPEN - CLEAR
ls.plant(sk, woods, ALL, keep_clear=CLEAR)
# the last row: tops of trees cut by the border (as Woodstock's south edge), not a strip of grass
run = []
for x in range(W + 1):
    if x < W and sk.get(x, H - 1) == "." and sk.get(x, H - 2) in "T." and (x, H - 1) not in CLEAR:
        run.append(x)
        continue
    for cx in run[:len(run) - len(run) % 2]:
        sk.set(cx, H - 1, "T")
    run = []
# saplings on the brook's banks above the pond (alder and birch) and along the mill's ridge
ls.sapling_stand(sk, ls.rect(3, 4, 9, 8) | ls.rect(14, 4, 21, 7), seed=1630, density=0.35,
                 keep_clear=CLEAR)

# --- gardens, the lawns, accents ---------------------------------------------------------------
BEDS = [((11, 13), 2), ((20, 16), 4), ((20, 18), 3),        # by the player's door; the Leblancs' garden
        ((6, 16), 2), ((23, 4), 3), ((31, 21), 3),          # the lawn's edge; the ridge; by the gate
        ((26, 20), 2), ((11, 20), 2), ((5, 6), 2)]          # the pond's bank; the lane; the back yard
for i, ((x, y), n) in enumerate(BEDS):
    ls.flower_bed(sk, x, y, n, seed=1610 + i, keep_clear=CLEAR - RING)
ls.nestle(sk, land - ls.rect(0, 20, W - 1, H - 1), 3, seed=1620, min_gap=7, keep_clear=CLEAR)
for (x, y) in [(31, 11), (32, 13)]:                  # the mill yard: logs waiting (boulders for now)
    if sk.get(x, y) == ".":
        sk.set(x, y, "b")

# --- sign posts (their text: design/maps/HomeTown_0.events.toml) -------------------------------
SIGNS = {
    "PlayersMailbox": (11, 13),      # right of the player's door
    "NeighboursMailbox": (13, 19),   # left of the Leblancs' door
}
for name, (x, y) in SIGNS.items():
    assert sk.get(x, y) in ".*", f"{name}'s spot ({x},{y}) is {sk.get(x, y)!r}, not grass"
    sk.set(x, y, "s")

out = os.path.join(HERE, "HomeTown_0.txt")
sk.save(out)
print("wrote", out)
for r in sk.rows:
    print("".join(r))
