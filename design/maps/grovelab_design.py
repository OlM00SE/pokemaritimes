"""GroveLab: dev test map for natural forests and open ground. Writes design/maps/GroveLab.txt.

Run:  python design/maps/grovelab_design.py
      python dev/mapgen.py build design/maps/GroveLab.txt --fresh [--apply]

A woodland meadow (not linked into the world; tests warp in) that uses every landscape helper
and flora piece (dev/mapkit/landscape.py, flora.py):
  - forest on three sides whose inner edges wave in bays and promontories: aligned canopy inside,
    offset fringe trees where the edge doesn't fit the tree grid, saplings in thin slivers
  - a clearing cut into the north-east woods, reached by the trail, with a flower bed and a boulder
  - a rounded free-standing grove west of centre, and a lone pair of trees on the meadow
  - a tall-grass meadow with stray tufts at its edge (Route 116's feathered fringe)
  - a young sapling grove in the south-west (Route 116's orchard of 1x2 saplings)
  - flower beds where the trail opens out, and boulders tucked into the forest's inner corners
The trail runs from the spawn (west edge) to the clearing; everything open is reachable on foot.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.sketch import Sketch
from mapkit import landscape as ls

W, H = 40, 32
sk = Sketch("GroveLab", ["." * W for _ in range(H)], [
    "// GroveLab - dev map for natural forests and open ground (generated by design/maps/grovelab_design.py)",
    "// legend: . grass  , tall grass  = path  : sand  ~ river/lake  o pond  T forest  r rock in water",
    "//         * flowers  b boulder  y sapling (2-3 tall)  v < > ledges  # keep"])

# --- the trail: spawn (1,16) -> east, then north into the clearing ---
TRAIL = ls.rect(0, 16, 21, 17) | ls.rect(20, 9, 21, 17) | ls.rect(20, 9, 31, 10) | ls.rect(30, 6, 31, 10)
for x, y in TRAIL:
    sk.set(x, y, "=")
CLEAR = ls.around(TRAIL, 1) | ls.rect(0, 14, 3, 19)       # nothing grows on or right beside the trail

# --- forest: three wavy edges, a clearing cut into the north-east, a free-standing grove ---
woods = (ls.forest_edge(0, 0, W - 1, 7, "S", amp=4, seed=11)           # north woods
         | ls.forest_edge(28, 0, W - 1, H - 1, "W", amp=6, seed=12)    # east woods
         | ls.forest_edge(0, 24, W - 1, H - 1, "N", amp=4, seed=13))   # south woods
woods -= ls.blob(33, 4.5, 4.5, 3.2, seed=14, wobble=0.25)               # the clearing
grove = ls.blob(9, 11.5, 5, 3.2, seed=15, wobble=0.25)                 # rounded grove
pair = ls.rect(24, 20, 27, 21)                                          # a lone pair
ls.plant(sk, woods | grove | pair, ls.rect(0, 0, W - 1, H - 1), keep_clear=CLEAR)

# --- open ground ---
ls.meadow(sk, ls.blob(13, 21, 5.5, 2.8, seed=17, wobble=0.3), seed=18, tufts=4, keep_clear=CLEAR)
# a young grove where the trail turns north: saplings coming up between the old woods and the trail
ls.sapling_stand(sk, ls.rect(23, 11, 29, 16), seed=20, density=0.7, keep_clear=CLEAR)
FLOWERS = [((34, 4), 5), ((17, 13), 3), ((4, 14), 4), ((29, 19), 1), ((19, 6), 2), ((2, 21), 1)]
for i, ((x, y), n) in enumerate(FLOWERS):
    ls.flower_bed(sk, x, y, n, seed=30 + i, keep_clear=CLEAR)
ls.nestle(sk, ls.rect(0, 0, W - 1, H - 1), 5, seed=21, min_gap=7, keep_clear=CLEAR)

out = os.path.join(HERE, "GroveLab.txt")
sk.save(out)
print("wrote", out)
