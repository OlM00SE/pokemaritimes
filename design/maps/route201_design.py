"""Route 201: the Meduxnekeag valley (milestone 16). Writes design/maps/Route201_1.txt.

Run:  python design/maps/route201_design.py
      python dev/mapgen.py build design/maps/Route201_1.txt --fresh [--apply]

Built from the corridor plan's underlay (design/region/corridor.toml: 52x28, an inset of the
start valley; `dev/corridor.py underlay "Route 201"`). The geography, as the plan has it: the
Meduxnekeag runs east the whole way, from HomeTown (the seam: rows 14-17) to Woodstock (rows
16-19), with the road on its south bank (rows 22-23 at both seams). Hardwood hills on both
sides; the valley floor opens into an intervale where the creek swings north.

Two ways along the valley, as the real one has:
  * the road on the south bank: past the farm on the intervale (its hay fields, the farmhouse,
    a gravel bar on the inside of the meander's bend), straight through to Woodstock;
  * the riverside trail on the north bank, for explorers: from HomeTown's mill along the creek,
    a meadow under the hardwood slope (a ledge drops from it onto the trail, where Bug Catcher
    Ross waits), the terraced glade above the bridge, the regrowing cutblock, the beaver pond,
    then along the bank into Woodstock's north bank.
  * the farm lane crosses the creek on a plank bridge and joins them.
Seams: west (HomeTown_0, offset -2): trees on rows 0-11 (the mill yard beyond stays closed:
HomeTown's exit gate covers the trail and the road), the trail on rows 12-13, the creek 14-17,
the road 22-23. East (Woodstock_2, offset 14): trees on rows 0-13 (even grid), the bank 14-15,
the creek 16-19, the road 22-23, trees on rows 25-26 (odd grid) and tree tops on row 27.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.project import Project
from mapkit.sketch import Sketch
from mapkit.geo import Plan
from mapkit import landscape as ls, stamps

W, H = 52, 28
p = Project()
cat = stamps.catalog(p)
under = Plan().underlay("Route 201")
assert (len(under[0]), len(under)) == (W, H), "the plan's size changed"
sk = Sketch("Route201_1", ["." * W for _ in range(H)], [
    "// Route 201 - the Meduxnekeag valley (generated by design/maps/route201_design.py)",
    "// legend: . grass  , tall grass  = path  : sand  ~ creek  T forest  * flowers  b boulder",
    "//         y sapling  s sign  r rock  H bridge  B building  v ledge  # keep"])
ALL = ls.rect(0, 0, W - 1, H - 1)

# --- the creek: per column (top row, bottom row) ---------------------------------------------
SPANS = [((0, 4), (14, 17)),      # the seam with HomeTown (its rows 16-19)
         ((5, 7), (13, 17)),      # a pool below the seam
         ((8, 10), (13, 16)), ((11, 12), (12, 15)), ((13, 15), (11, 15)),
         ((16, 21), (10, 13)),    # a boulder mid-stream
         ((22, 29), (9, 12)),     # the meander's apex, straight: the bridge at 26-27
         ((30, 31), (9, 13)), ((32, 34), (10, 13)), ((35, 36), (11, 14)),
         ((37, 42), (12, 15)),    # a straight reach under the beaver pond's slope
         ((43, 44), (13, 16)), ((45, 46), (14, 17)), ((47, 47), (15, 18)),
         ((48, 51), (16, 19))]    # the seam with Woodstock (its rows 30-33)
TOP = {}
CREEK = set()
for (x0, x1), (t, b) in SPANS:
    for x in range(x0, x1 + 1):
        TOP[x] = t
        CREEK |= ls.rect(x, t, x, b)
ROCKS = ls.rect(18, 11, 19, 12)
BRIDGE = ls.rect(26, 9, 27, 12)
# the beaver pond under the hardwood slope, its lodge (a rock for now)
POND = (ls.rect(41, 4, 47, 7) | ls.rect(42, 3, 46, 3) | ls.rect(40, 5, 40, 6)
        | ls.rect(43, 8, 46, 8))
LODGE = ls.rect(43, 5, 44, 6)
WATER = CREEK | POND
# the gravel bar on the inside of the bend (the water bulges into it, the sand runs a tile past)
BAR = ls.rect(22, 13, 24, 13) | ls.rect(21, 14, 24, 14)

# --- the road, the farm lane, the trail ---------------------------------------------------------
# a gentle arch up the intervale toward the farm lane: (x0, x1, top row), two rows each
ROAD_SPANS = [(0, 9, 22), (8, 19, 21), (18, 31, 20), (30, 41, 21), (40, W - 1, 22)]
# (the steps fall so each stretch of the slope below is an even number of columns: whole trees)
ROAD = set()
for x0, x1, t in ROAD_SPANS:
    ROAD |= ls.rect(x0, t, x1, t + 1)
ROAD_BOTTOM = {x: max(y for xx, y in ROAD if xx == x) for x in range(W)}
LANE = ls.rect(26, 14, 27, 19)                    # from the road up to the bridge's south end
TRAIL = ls.rect(26, 4, 27, 7)                     # from the bridge's north end up into the glade

# --- the farm: (stamp, top-left, room) --------------------------------------------------------
BUILDINGS = [("house_oldale", (13, 16), "Route201_Farmhouse")]      # door (14,19)
FOOT, STUBS = set(), set()
for name, (x, y), room in BUILDINGS:
    dx, fy = sk.place(p, name, x, y, room)
    FOOT |= cat[name].footprint(x, y)
    fy += 1
    while (dx, fy) not in ROAD:
        STUBS.add((dx, fy))
        fy += 1
PATHS = ROAD | LANE | TRAIL | STUBS

for (x, y) in WATER - ROCKS - LODGE:
    sk.set(x, y, "~")
for (x, y) in ROCKS | LODGE:
    sk.set(x, y, "r")
for (x, y) in BRIDGE:
    sk.set(x, y, "H")
for (x, y) in PATHS:
    sk.set(x, y, "=")
for (x, y) in BAR:
    sk.set(x, y, ":")

# --- elevation: ledges down the north slope -----------------------------------------------------
# the meadow's lip drops onto the riverside trail (Ross waits below); the glade is a terrace
# with the trail climbing through its middle
LEDGES = ls.rect(3, 9, 9, 9) | ls.rect(20, 5, 24, 5) | ls.rect(29, 5, 32, 5)
for (x, y) in LEDGES:
    sk.set(x, y, "v")

# --- open ground: the valley floor, the north side's clearings; woods elsewhere ---------------
N_BANK = set()                                    # the riverside trail: 2-3 rows over the creek
for x in range(0, W):
    depth = 2
    N_BANK |= ls.rect(x, TOP[x] - depth, x, TOP[x] - 1)
MEADOW = ls.blob(7, 6.5, 4.8, 3.4, seed=2101, wobble=0.25) & ls.rect(2, 3, 12, 10)
GLADE = ls.blob(26, 5.5, 7.5, 2.6, seed=2102, wobble=0.25) & ls.rect(18, 3, 34, 8)
CUTBLOCK = ls.blob(37, 7.5, 3.2, 2.8, seed=2103, wobble=0.3) & ls.rect(33, 4, 40, 11)
POND_GLADE = ls.blob(44, 6, 5.2, 3.3, seed=2104, wobble=0.2) & ls.rect(39, 2, 49, 10)
FLATS = ls.blob(43, 11.5, 5, 1.5, seed=2105, wobble=0.2)
VALLEY = {(x, y) for x in range(W) for y in range(13, ROAD_BOTTOM[x] + 2)} - ls.rect(0, 13, 7, 13)
# the slope south of the road, in segments: each on the tree grid its verge allows (the first
# row below the verge starts a band), its edge stepped into bays
SOUTH = []
seg = 0
for x in range(W + 1):
    if x == W or (x > seg and ROAD_BOTTOM[x] != ROAD_BOTTOM[seg]):
        first = ROAD_BOTTOM[seg] + 2
        SOUTH.append((ls.rect(seg, first, x - 1, H - 1), first % 2))
        seg = x
for i, (area, par) in enumerate(SOUTH):
    xs = [c[0] for c in area]
    first = min(c[1] for c in area)
    VALLEY -= ls.forest_edge(min(xs), first, max(xs), H - 1, "N", amp=2, seed=2150 + i)
OPEN = N_BANK | MEADOW | GLADE | CUTBLOCK | POND_GLADE | FLATS | VALLEY
OPEN |= ls.rect(10, 6, 14, 9)                     # the meadow opens onto the trail at its east end
OPEN -= ls.rect(0, 0, 0, 11)                      # the west seam: woods above the trail
OPEN -= ls.rect(W - 2, 0, W - 1, 13)              # the east seam: woods above the bank
# hedgerows and groves on the valley floor: between the fields, by the farmhouse, at the bends
# (on the tree grid: whole 2-row bands starting on even rows, or plant drops them)
GROVES = (ls.rect(8, 18, 11, 19) | ls.rect(30, 16, 33, 17) | ls.rect(40, 18, 43, 19)
          | ls.rect(18, 14, 19, 15) | ls.rect(36, 18, 37, 19))
OPEN -= GROVES
OPEN |= PATHS | ls.around(BRIDGE, 1)

RING = ls.around(FOOT, 1) - FOOT
CLEAR = (ls.around(PATHS, 1) | RING | FOOT | ls.around(WATER, 1) | ls.around(BRIDGE, 1)
         | ls.around(BAR, 1) | ls.ledge_clearance(sk))
land = ALL - WATER
woods = land - OPEN - CLEAR
SOUTH_ALL = set().union(*(a for a, _ in SOUTH))
ls.plant(sk, woods, ALL - SOUTH_ALL, keep_clear=CLEAR)
for area, par in SOUTH:
    ls.plant(sk, woods, area, parity=(0, par), saplings=False, keep_clear=CLEAR)
run = []                                          # the last row: tops of trees cut by the border
for x in range(W + 1):
    if x < W and sk.get(x, H - 2) == "T" and sk.get(x, H - 1) == ".":
        run.append(x)
        continue
    for cx in run[:len(run) - len(run) % 2]:
        sk.set(cx, H - 1, "T")
    run = []

# --- the cutblock regrowing, tall grass, accents ------------------------------------------------
ls.sapling_stand(sk, CUTBLOCK, seed=2111, density=0.7, keep_clear=CLEAR)
ls.meadow(sk, CUTBLOCK & ls.blob(36.5, 7, 3, 2.4, seed=2112), seed=2113, tufts=1, keep_clear=CLEAR)
ls.meadow(sk, ls.blob(8, 5.5, 3.8, 2.2, seed=2114, wobble=0.3), seed=2115, tufts=2,
          keep_clear=CLEAR)                                         # the meadow above the ledge
ls.meadow(sk, ls.blob(22, 7, 2.5, 1.0, seed=2116) | ls.blob(31, 3.5, 2.2, 1.0, seed=2117),
          seed=2118, tufts=2, keep_clear=CLEAR)                     # the glade's benches
# the hay fields on the intervale, either side of the farm lane
ls.meadow(sk, ls.rect(17, 16, 23, 19) | ls.rect(29, 15, 36, 16) | ls.rect(34, 17, 37, 19),
          seed=2119, tufts=3, keep_clear=CLEAR)
ls.meadow(sk, ls.blob(44, 15.5, 2.0, 1.0, seed=2120), seed=2121, tufts=1, keep_clear=CLEAR)

for i, ((x, y), n) in enumerate([((12, 19), 2), ((16, 15), 3), ((24, 16), 2), ((30, 7), 3),
                                 ((47, 10), 3), ((7, 12), 2), ((3, 16), 2), ((43, 20), 2),
                                 ((20, 8), 2), ((49, 21), 2)]):
    ls.flower_bed(sk, x, y, n, seed=2130 + i, keep_clear=CLEAR - RING)
INNER = ls.rect(2, 0, W - 3, H - 1)               # never on a seam's column
ls.nestle(sk, INNER - ls.rect(0, 13, W - 1, H - 1), 5, seed=2140, min_gap=7, keep_clear=CLEAR)
ls.nestle(sk, INNER & ls.rect(0, 13, W - 1, 21), 4, seed=2141, min_gap=10, keep_clear=CLEAR)

# --- the route sign (its text: design/maps/Route201_1.events.toml) -----------------------------
SIGN = (3, 21)
assert sk.get(*SIGN) == ".", f"the sign's spot {SIGN} is {sk.get(*SIGN)!r}"
sk.set(*SIGN, "s")

out = os.path.join(HERE, "Route201_1.txt")
sk.save(out)
print("wrote", out)
for r in sk.rows:
    print("".join(r))
