"""Route 201 - "the old logging road": design script that writes design/maps/Route201_1.txt.

Run:  python design/maps/route201_design.py      then  python dev/mapgen.py build design/maps/Route201_1.txt
      (no --fresh: trees on the old grid stay put; read the routes/landscape/reach lines and
      dev/out/Route201_1_preview_diff.png, then --apply)

The first route out of HomeTown: an old logging road through rural New Brunswick woods.
  - A sand road runs from HomeTown's lane (x 10-11 at the top) to Woodstock's road (rows 14-15
    at the east edge), so the three maps read as one road.
  - Mixed woods on both sides, with natural edges (bays, headlands, offset fringe trees).
  - The first tall grass: meadows in the clearings beside the road.
  - A cutblock regrowing with saplings (the forestry village's work), a beaver pond with reeds,
    glacial boulders, and flowers along the verges.
  - A small terrace: a ledge below the road drops into the central meadow, a one-way shortcut
    toward Woodstock, as the old map's ledges were.

Seams this design must honour:
  north (HomeTown_0, offset 0): only x 10-11 are open (HomeTown's sand patch runs into the road)
  east  (Woodstock_2, offset 0): only rows 14-16 are open (sand road on 14-15, grass on 16);
        Woodstock's cliff runs along row 17 and Tom's cliff corner continues it here (x 43-49,
        rows 15-19, kept as is)
  south, west: no connection (forest)
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.sketch import Sketch
from mapkit import landscape as ls

W, H = 50, 20
ALL = ls.rect(0, 0, W - 1, H - 1)
sk = Sketch("Route201_1", ["." * W for _ in range(H)], [
    "// Route 201 - the old logging road (generated by design/maps/route201_design.py)",
    "// legend: . grass  , tall grass  = path  : sand road  o pond  T forest",
    "//         * flowers  b boulder  y sapling (2-3 tall)  v ledge (jump south)  # keep"])
f = sk.fill

# --- kept as hand-painted: Tom's cliff corner continuing Woodstock's row-17 cliff, the tree on
# it, and the two saplings at its foot ---
CLIFF = ls.rect(43, 15, 45, 17) | ls.rect(46, 17, 49, 17) | ls.rect(42, 18, 49, 19)
for x, y in CLIFF:
    sk.set(x, y, "#")

# --- the HomeTown gap: the trees either side of the lane stay exactly as they are. (The grammar
# wants a grass verge between trees and sand, which would open the tree band under HomeTown.)
GAP = ls.rect(8, 0, 9, 1) | ls.rect(12, 0, 13, 1)
for x, y in GAP:
    sk.set(x, y, "#")

# --- the beaver pond (unchanged cells; pond shores are still learned, not shape-resolved) ---
POND = ls.rect(40, 2, 43, 3) | ls.rect(40, 4, 45, 6)
for x, y in POND:
    sk.set(x, y, "o")

# --- the logging road (2 wide), HomeTown -> Woodstock: south out of the village, east along the
# foot of the north woods, a jog south at the old cutblock, east past the pond, and down to
# Woodstock's road. The last bend is at x 45-46 so the east edge keeps whole trees at x 48-49.
ROAD = (ls.rect(10, 0, 11, 7) | ls.rect(10, 6, 27, 7) | ls.rect(26, 6, 27, 11)
        | ls.rect(26, 10, 46, 11) | ls.rect(45, 10, 46, 14) | ls.rect(45, 14, 49, 14)
        | ls.rect(46, 15, 49, 15))
for x, y in ROAD:
    sk.set(x, y, ":")

# --- a terrace: the strip below the road's first leg is a step higher than the central meadow;
# its ledge is a one-way shortcut down into the grass
LEDGE = ls.rect(13, 10, 21, 10)
for x, y in LEDGE:
    sk.set(x, y, "v")

VERGE = ls.around(ROAD, 1) - ls.rect(0, 0, W - 1, 1)       # grass beside the road (not under HomeTown)
KEEP = (ROAD | VERGE | CLIFF | GAP | POND | (ls.around(POND, 1) - ls.rect(0, 0, W - 1, 1))
        | ls.ledge_clearance(sk) | ls.rect(46, 16, 49, 16))

# --- forest by default; the road runs through it on a one-tile verge, and the woods open into
# clearings beside it ---
INSIDE = ls.rect(2, 2, W - 3, H - 3)          # clearings never reach the map's closed edges
NW_MEADOW = ls.blob(6, 9.5, 3.8, 3.4, seed=2021, wobble=0.3) & INSIDE  # west of the village lane
CLEARING = ls.blob(20, 3.8, 4.6, 2.2, seed=2022, wobble=0.3) & INSIDE  # a sunny clearing by the road
TERRACE = ls.blob(18.5, 12, 7.2, 4.0, seed=2023, wobble=0.25) & INSIDE     # the ledge and the meadow below
POND_GLADE = ls.blob(39.5, 5.5, 6.8, 3.8, seed=2024, wobble=0.25) & INSIDE  # around the beaver pond
CUTBLOCK = ls.blob(34, 14.5, 5.8, 2.7, seed=2025, wobble=0.3) & INSIDE     # logged a few years ago
woods = ALL - NW_MEADOW - CLEARING - TERRACE - POND_GLADE - CUTBLOCK
woods |= ls.rect(33, 2, 35, 3)                # a headland of the north woods between reeds and road
ls.plant(sk, woods, ALL, keep_clear=KEEP)

# --- the cutblock regrowing: young trees coming up through the tall grass (Route 116's grove) ---
ls.sapling_stand(sk, CUTBLOCK, seed=2041, density=0.8, keep_clear=KEEP)

# --- open ground: the first tall grass ---
ls.meadow(sk, NW_MEADOW & ls.blob(5.5, 9.5, 3.2, 3.2, seed=2031, wobble=0.3), seed=2032, tufts=2,
          keep_clear=KEEP)
ls.meadow(sk, ls.blob(18, 13.5, 7, 2.6, seed=2033, wobble=0.3), seed=2034, tufts=3,
          keep_clear=KEEP - ls.ledge_clearance(sk) | LEDGE)              # below the ledge
ls.meadow(sk, ls.blob(35.5, 6, 2.8, 3.0, seed=2035, wobble=0.3), seed=2036, tufts=2,
          keep_clear=KEEP)                      # reeds by the pond (the grammar keeps a grass rim)
ls.meadow(sk, CUTBLOCK & ls.blob(35, 15, 4.6, 2.2, seed=2037, wobble=0.3), seed=2038, tufts=1,
          keep_clear=KEEP)
ls.meadow(sk, ls.blob(21.5, 3.6, 2.7, 1.5, seed=2039, wobble=0.3), seed=2040, tufts=2,
          keep_clear=KEEP)                                              # a patch in the clearing
# flowers on the verges where the road bends and in the clearings; boulders (glacial erratics)
# against the woods
for i, ((x, y), n) in enumerate([((17, 3), 3), ((24, 9), 2), ((9, 13), 1), ((42, 8), 3),
                                 ((28, 13), 2), ((3, 12), 1)]):
    ls.flower_bed(sk, x, y, n, seed=2050 + i, keep_clear=KEEP)
ls.nestle(sk, ALL, 5, seed=2060, min_gap=8, keep_clear=KEEP)

out = os.path.join(HERE, "Route201_1.txt")
sk.save(out)
print("wrote", out)
