"""Route 203 — "Saint John River valley": design script that writes design/maps/Route203_1.txt.

Run:  python design/maps/route203_design.py      then  python dev/mapgen.py build design/maps/Route203_1.txt
      (no --fresh: the build keeps the existing trees, so the diff stays small; check
      dev/out/Route203_1_preview_diff.png, then --apply)

Terraces (milestone 4): the riverside meadow is a natural levee, a step above the valley floor;
its ledge scarp drops onto the valley trail. In the west, the grove stands on a wooded bench
that drops into the tall grass. Tested in-game by dev/tests/ingame_ledges.py Route203_1.

Seams this design must honour (from the neighbours, see dev/mapkit seam extraction):
  west  (Fredericton, rows 0..28): rows 0-2 grass, 3-6 river, 7-28 grass
  east  (Route203_1_2, rows 0..27): 0-1 forest, 2 grass, 3-6 river, 7-11 grass, 12+ forest
  south (Route101_2 at x 40..59):   forest except an opening at x 48..51
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.sketch import Sketch

W, H = 60, 40
sk = Sketch("Route203_1", ["." * W for _ in range(H)], [
    "// Route 203 - Saint John River valley (generated by design/maps/route203_design.py)",
    "// legend: . grass  , tall grass  = path  : sand (a beach where it meets ~)  ~ river  o pond",
    "//         T forest  r rock in water (2x2)  # keep",
    "//         v ledge (jump south)  < ledge (jump west)  > ledge (jump east)"])
f = sk.fill

# --- base: forest everywhere, then carve the valley ---
f(0, 0, W - 1, H - 1, "T")

# north bank: forest band (one row of 2x2 trees) + grassy bank strip along the river
f(0, 0, 5, 1, ".")                 # matches Fredericton's open grass at the seam
f(0, 2, W - 1, 2, ".")             # riverside strip, continuous to Route203_1_2 row 2
# (the river itself is drawn below, under "natural banks", after the meadow it cuts through)

# south bank: open valley floor
f(0, 7, W - 1, 11, ".")            # riverbank meadow; east rows 7-11 match the exit opening
f(0, 12, 53, 28, ".")              # main valley
f(0, 25, 5, 28, ".")               # west seam rows 25-28 are open in Fredericton
f(44, 12, 53, 37, ".")             # land toward the south exit

# --- natural banks (milestone 5): the river's width varies between 3 and 6 tiles ---
# Each column's first and last water row. The seams keep rows 3-6 (x 0-3 and 56-59), so the
# river still lines up with Fredericton and Route203_1_2. Grass promontories push the north
# bank in; on the south side the bank swings out into a bay (x 8-12, the outside of a bend),
# a point-bar beach (x 17-23), and a small bay below the east trail (x 36-41).
def profile(default, runs):
    """Per-column row from (x0, x1, row) runs."""
    out = {x: default for x in range(W)}
    for x0, x1, row in runs:
        out.update({x: row for x in range(x0, x1 + 1)})
    return out


# promontories with rounded tips (4 -> 5 -> 4)
NORTH = profile(3, [(10, 11, 4), (12, 13, 5), (14, 15, 4), (22, 26, 4), (33, 37, 4),
                    (44, 44, 4), (45, 47, 5), (48, 49, 4)])
# the bay on the outside of the bend (7 -> 8 -> 7), a two-tile headland, the beach's bulge, the
# small east bay where a creek comes in (7 -> 8 -> 7), and a rounded headland near the east seam (5 -> 4 -> 5)
SOUTH = profile(6, [(5, 5, 7), (6, 11, 8), (12, 13, 7), (16, 23, 7), (34, 35, 7), (36, 37, 8),
                    (38, 41, 7), (49, 50, 5), (51, 54, 4), (55, 55, 5)])
for x in range(W):
    f(x, 3, x, 8, ".")
    f(x, NORTH[x], x, SOUTH[x], "~")

# the point-bar beach: the river bulges into it (x 16-23). Along the water the edge is drawn on
# the sand (11C), and the ends turn under the bank (13E at x 16, 13D at x 23), so the sand runs
# one tile past the water on each side. Kept clear of the trees at x 26+ and of the trail.
f(15, 8, 24, 8, ":")
f(16, 9, 23, 9, ":")
f(18, 10, 22, 10, ":")

# reeds on the promontory tips (tall grass keeps a grass row between itself and the water)
f(11, 2, 14, 2, ","); f(12, 3, 13, 3, ",")
f(45, 2, 47, 2, ","); f(45, 3, 47, 3, ",")

# rocks standing in the river (2x2, water on every side)
f(5, 4, 6, 5, "r")
f(29, 4, 30, 5, "r")

# --- the trail ---
f(0, 10, 17, 11, "=")              # from Fredericton heading east
f(16, 10, 17, 17, "=")             # dips south around the first grove
f(16, 16, 39, 17, "=")             # along the valley floor
f(38, 9, 39, 17, "=")              # back up toward the river
f(38, 9, W - 1, 10, "=")           # east to Route203_1_2
f(48, 16, 49, 39, "=")             # branch south to Route101_2
f(48, 38, 51, 39, ".")             # the opening itself (x 48..51)
f(50, 30, 51, 39, ".")

# --- groves (even-sized so whole 2x2 trees fit) ---
f(4, 14, 11, 19, "T")              # west grove, up on the wooded bench (see ledges below)
f(20, 20, 31, 27, "T")             # central grove
f(26, 8, 33, 11, "T")            # small riverside stand, on the levee terrace
f(40, 20, 43, 25, "T")             # stand beside the pond
f(0, 30, 45, 39, "T")              # southern forest (left edge rows 29+ have no neighbour)
f(52, 12, 59, 39, "T")             # eastern forest (matches Route203_1_2 rows 12+)

# --- tall grass (encounters) ---
f(2, 22, 13, 27, ",")
f(12, 13, 15, 15, ",")
f(32, 18, 37, 27, ",")
f(44, 26, 47, 33, ",")
f(19, 12, 25, 14, ",")

# --- a small kettle pond ---
f(34, 20, 39, 23, "o")
f(35, 24, 38, 24, "o")

# --- terraces (ledges: v jumps south, < west, > east; the high ground is behind the arrow) ---
# The river's natural levee: the meadow along the water stands a step above the valley floor.
# Its scarp wraps the tall grass and the riverside stand, stepping down once in the middle, and
# drops onto the valley trail. The trail's two climbs (x 16-17 and x 38-39) are the ways back up.
f(18, 12, 18, 14, "<")             # west flank, over the trail's first climb
f(18, 15, 29, 15, "v")             # lower scarp: 08D corner, then onto the trail at row 16
f(29, 14, 37, 14, "v")             # stair step up (06E over 08E), then the upper scarp
f(37, 11, 37, 13, ">")             # east flank, over the trail's second climb (08E at the foot)
# A wooded bench in the west: the grove stands on a terrace that drops into the tall grass.
# Its open sides (north, and the west seam) are the ways up.
f(2, 21, 13, 21, "v")              # south scarp, landing in the tall grass
f(13, 16, 13, 20, ">")             # east flank (08E where it meets the scarp)

# keep the path clear of anything drawn after it
for x0, y0, x1, y1 in ((16, 16, 39, 17), (48, 16, 49, 37)):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if sk.get(x, y) not in ("=",):
                sk.set(x, y, "=")

# --- natural groves and open ground (milestone 6, mapkit/landscape.py) ---
# The valley floor south of the trail had box groves, a ruler-straight forest wall and
# rectangles of tall grass. It is replanted here; the scope is x 0-47, y 18-34 plus the wooded
# bench. Rows 35-39 and the east forest stay as they are (the Route101_2 and Route203_1_2 seams);
# so do the trail, the pond, the ledges with their approach and landing tiles, and the open
# grass along the west seam (Fredericton, rows 7-28).
from mapkit import landscape as ls
FLOOR = ls.rect(0, 18, 47, 34)
KEEP = (ls.around(ls.cells_of(sk, "="), 1) | ls.ledge_clearance(sk) | ls.cells_of(sk, "v<>o")
        | ls.rect(0, 0, 1, 28) | ls.rect(0, 35, 59, 39))
for x, y in ls.cells_of(sk, ",", FLOOR):          # the old tall-grass rectangles, redrawn below
    sk.set(x, y, ".")
# The southern forest's edge comes and goes in bays and headlands (rows 27-31, around the old
# straight edge at row 29). Its trees sit on odd rows (the forest starts at row 29), so it is
# replanted on that grid, in whole bands (rows 27-34, x 0-43); rows 35-39 stay, and so does the
# column of trees at x 44-45 beside the south branch.
SOUTH = ls.rect(0, 27, 43, 34)
GROVES = ls.rect(0, 18, 47, 26) | ls.rect(2, 13, 12, 20)
for x, y in ls.cells_of(sk, "Ty", SOUTH | GROVES):   # the old box groves (one straddles both areas)
    sk.set(x, y, ".")                                   # and the straight forest edge, replanted below
south =(ls.forest_edge(2, 27, 43, 34, "N", amp=4, seed=203) | ls.rect(0, 29, 1, 34)
         | ls.rect(30, 27, 31, 28))               # a lone tree standing out from the edge
ls.plant(sk, south, SOUTH, parity=(0, 1), keep_clear=KEEP)
# The groves become rounded stands of about the old size: on the wooded bench, in the middle of
# the valley (with a sheltered notch on its sunny south-west side), and beside the pond.
bench =ls.blob(7.5, 16.5, 4.4, 3.3, seed=204, wobble=0.35)
middle = ls.blob(26, 22.5, 6.4, 3.9, seed=205, wobble=0.25) - ls.blob(20.5, 25.5, 2, 1.6, seed=206)
pond = ls.blob(42, 22.5, 2.4, 3.6, seed=207, wobble=0.2)
ls.plant(sk, bench | middle | pond, GROVES, keep_clear=KEEP)
# Tall grass: the meadow below the bench's scarp (its landing rows stay grassy), the reeds
# west and south of the pond, and the strip along the south branch, each with stray tufts.
ls.meadow(sk, ls.rect(2, 22, 13, 23) | ls.blob(8, 25, 6.5, 2.6, seed=208, wobble=0.3),
          seed=209, tufts=3, keep_clear=KEEP - ls.ledge_clearance(sk))
ls.meadow(sk, ls.blob(34, 23, 3, 4.8, seed=210, wobble=0.3), seed=211, tufts=2, keep_clear=KEEP)
ls.meadow(sk, ls.blob(45.5, 30, 2.2, 4.6, seed=212, wobble=0.25), seed=213, tufts=2, keep_clear=KEEP)
# Young trees coming up in the open ground between the pond stand and the south branch.
ls.sapling_stand(sk, ls.rect(44, 18, 46, 25), seed=214, density=0.6, keep_clear=KEEP)
# Flowers where the trail opens out and in the grove's sunny notch; boulders tucked into the
# forest's inner corners.
for i, ((x, y), n) in enumerate([((20, 26), 4), ((14, 19), 3), ((30, 19), 2), ((38, 27), 3),
                                 ((4, 28), 1), ((28, 29), 1)]):
    ls.flower_bed(sk, x, y, n, seed=220 + i, keep_clear=KEEP)
ls.nestle(sk, FLOOR, 4, seed=230, min_gap=8, keep_clear=KEEP)

out = os.path.join(HERE, "Route203_1.txt")
sk.save(out)
print("wrote", out)
