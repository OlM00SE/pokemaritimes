"""TownLab: dev test map for building stamps. Writes design/maps/TownLab.txt.

Run:  python design/maps/townlab_design.py
      python dev/mapgen.py build design/maps/TownLab.txt --fresh [--apply]

A small village (not linked into the world; tests warp in) with every stamp in the catalog
(dev/mapkit/stamps.toml), each door wired to its own room by `mapgen --apply`:
  - the main street: the lab, the gym, the Pokémon Center and the Mart face it from the north;
  - the south street: five houses (two-storey with the door on either side, small, small and
    wide, the brown-roofed Oldale house);
  - a lane down the cross street to the wide house by the pond.
Woods close the village on every side; gardens, flowers and a few boulders between the houses.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.project import Project
from mapkit.sketch import Sketch
from mapkit import landscape as ls, stamps

W, H = 44, 34
p = Project()
cat = stamps.catalog(p)
sk = Sketch("TownLab", ["." * W for _ in range(H)], [
    "// TownLab - dev map for building stamps (generated by design/maps/townlab_design.py)",
    "// legend: . grass  , tall grass  = path  o pond  T forest  * flowers  b boulder  B building  # keep"])

# --- streets: the main street, the south street, the cross street and the lane to the pond ---
MAIN = ls.rect(4, 11, 39, 12)
SOUTH = ls.rect(4, 22, 39, 23)
CROSS = ls.rect(20, 11, 21, 31)
LANE = ls.rect(13, 30, 21, 31)
STREETS = MAIN | SOUTH | CROSS | LANE

# --- buildings: (stamp, top-left, room behind the door). Doors face the streets. ---
BUILDINGS = [
    ("lab", (5, 5), "TownLab_Lab"),                          # door (9,9), mat (9,10)
    ("gym", (13, 6), "TownLab_Gym"),                         # door (16,10)
    ("pokemon_center", (26, 7), "TownLab_PokemonCenter_1F"),  # door (27,10)
    ("mart", (33, 7), "TownLab_Mart"),                       # door (34,10)
    ("house_two_storey", (4, 16), "TownLab_TwoStorey_1F"),   # door (7,20), mat (7,21)
    ("house_small", (11, 18), "TownLab_SmallHouse"),         # door (12,21)
    ("house_small_wide", (24, 18), "TownLab_WideHouse"),     # door (26,21)
    ("house_oldale", (30, 18), "TownLab_OldaleHouse"),       # door (31,21)
    ("house_two_storey_left", (35, 16), "TownLab_TwoStoreyLeft_1F"),  # door (36,20), mat (36,21)
    ("house_wide", (11, 25), "TownLab_LeanTo"),              # door (13,29)
]
FOOT, STUBS = set(), set()
for name, (x, y), room in BUILDINGS:
    st = cat[name]
    dx, fy = sk.place(p, name, x, y, room)
    FOOT |= st.footprint(x, y)
    fy += 1
    while (dx, fy) in FOOT:                   # past a doormat
        fy += 1
    while (dx, fy) not in STREETS:            # a path from the door down to the street
        STUBS.add((dx, fy))
        fy += 1
for x, y in (STREETS | STUBS) - FOOT:
    sk.set(x, y, "=")
PATHS = (STREETS | STUBS) - FOOT
RING = ls.around(FOOT, 1) - FOOT
CLEAR = ls.around(PATHS, 1) | RING | FOOT

# --- the pond east of the lane ---
POND = ls.blob(31, 27.5, 5.5, 2.6, seed=41, wobble=0.25)
for x, y in POND - CLEAR:
    sk.set(x, y, "o")
CLEAR |= ls.around(POND, 1)

# --- woods on every side, with soft edges ---
woods = (ls.forest_edge(0, 0, W - 1, 4, "S", amp=2, seed=51)
         | ls.forest_edge(0, 0, 3, H - 1, "E", amp=1, seed=52)
         | ls.forest_edge(40, 0, W - 1, H - 1, "W", amp=1, seed=53)
         | ls.forest_edge(0, 30, W - 1, H - 1, "N", amp=2, seed=54))
grove = ls.rect(4, 26, 7, 29) | ls.rect(36, 24, 39, 25)
ls.plant(sk, (woods | grove) - CLEAR, ls.rect(0, 0, W - 1, H - 1), keep_clear=CLEAR)

# --- gardens and accents ---
for i, ((x, y), n) in enumerate([((17, 15), 4), ((9, 14), 3), ((24, 14), 3), ((33, 14), 3), ((26, 25), 2)]):
    ls.flower_bed(sk, x, y, n, seed=60 + i, keep_clear=CLEAR)
ls.nestle(sk, ls.rect(0, 0, W - 1, H - 1), 3, seed=72, min_gap=8, keep_clear=CLEAR)

out = os.path.join(HERE, "TownLab.txt")
sk.save(out)
print("wrote", out)
for r in sk.rows:
    print("".join(r))
