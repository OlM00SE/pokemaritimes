"""Woodstock: the confluence town (milestone 15). Writes design/maps/Woodstock_2.txt.

Run:  python design/maps/woodstock_design.py
      python dev/mapgen.py build design/maps/Woodstock_2.txt --fresh [--apply]

The first corridor map built from the plan of record (design/region/corridor.toml, 48x42, one
tile = 0.5 km, the town at world (0, 0)). The geography, as it really is:
  * the Saint John runs down the east side, from real data (the underlay's river, ~6 wide);
  * the Meduxnekeag comes in from the west (the seam with Route 201 at rows 30-33) and meets
    the Saint John at downtown, widening into its mouth;
  * downtown stands on the west bank, north of the creek's mouth; the highway keeps to the
    creek's south bank (the seams: Route 201 at rows 36-37, Route 202 at columns 25-26);
  * the far bank is wooded; north, the river valley toward Hartland (later) is woods for now.
The town:
  * Main Street runs north from the highway junction over the Meduxnekeag on a plank bridge
    (the real Main Street crosses the creek at its mouth) into downtown;
  * Water Street, the first street over the bridge: the Pokemon Center (east, by the river) and
    the Mart (west) face it, with the wide house beyond the Mart;
  * King Street, uphill: the wildlife station by the river, the garden house to the west, its
    community garden; the riverside green between the station and the Center;
  * Main Street ends in a clearing at the north edge of town, where the trail to Hartland is
    closed (a sign);
  * south of the creek: the highway in from Route 201 along the bank, south to Route 202.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.project import Project
from mapkit.sketch import Sketch
from mapkit.geo import Plan
from mapkit import landscape as ls, stamps

W, H = 48, 42
p = Project()
cat = stamps.catalog(p)
under = Plan().underlay("Woodstock")
assert (len(under[0]), len(under)) == (W, H), "the plan's size changed"
sk = Sketch("Woodstock_2", ["." * W for _ in range(H)], [
    "// Woodstock - the confluence town (generated by design/maps/woodstock_design.py)",
    "// legend: . grass  , tall grass  = path  ~ river  T forest  * flowers  b boulder  s sign"
    "  r rock  H bridge  B building  # keep"])

# --- water -----------------------------------------------------------------------------------
# The Saint John from the plan (real data): its cells east of column 35. The underlay's own
# Meduxnekeag is a straight diagonal; it is redrawn here as a creek that runs east along the
# valley floor (a straight stretch where Main Street crosses), then widens into its mouth.
RIVER = {(x, y) for y, row in enumerate(under) for x, ch in enumerate(row) if ch == "~" and x >= 35}
RIVER |= ls.rect(35, 19, 36, 23) - {(36, 19)}          # the west bank at the mouth, made even
# Route 202's river is a column wider at the seam (its 27 is our 43): the bottom row's east bank
# steps out to meet it, so the bank runs on across the seam (no walker reaches this bank)
RIVER |= {(43, H - 1)}
CREEK_ROWS = [  # (x0, x1, top row, bottom row) of the water, west to east
    (0, 4, 30, 33),       # the seam with Route 201 (the plan: rows 30-33)
    (5, 8, 29, 32),
    (9, 11, 29, 31),
    (12, 15, 28, 31),
    (16, 19, 28, 30),
    (20, 22, 27, 30),
    (23, 28, 27, 29),     # straight, under the bridge (columns 25-26)
    (29, 30, 26, 29),
    (31, 32, 25, 29),
    (33, 34, 24, 30),     # the mouth, into the Saint John
]
CREEK = set()
for x0, x1, t, b in CREEK_ROWS:
    CREEK |= ls.rect(x0, t, x1, b)
WATER = RIVER | CREEK
ROCKS = ls.rect(41, 8, 42, 9) | ls.rect(37, 33, 38, 34)  # two boulders in the big river

# --- streets ---------------------------------------------------------------------------------
HIGHWAY = ls.rect(0, 36, 26, 37) | ls.rect(25, 36, 26, H - 1)   # Route 201 -> junction -> Route 202
MAIN_S = ls.rect(25, 31, 26, 35)                                  # the junction up to the bridge
BRIDGE = ls.rect(25, 27, 26, 29)
MAIN_N = ls.rect(25, 5, 26, 25)                                   # downtown, north to the clearing
WATER_ST = ls.rect(12, 22, 31, 23)
KING_ST = ls.rect(5, 14, 33, 15)
STREETS = HIGHWAY | MAIN_S | MAIN_N | WATER_ST | KING_ST

# --- buildings: (stamp, top-left, room behind the door) --------------------------------------
# The station and both houses keep their rooms (and people, and warp ids); the Center and the
# Mart are new. Every door faces a street.
BUILDINGS = [
    ("pokemon_center", (28, 18), "Woodstock_PokemonCenter_1F"),  # door (29,21) on Water St
    ("mart", (20, 18), "Woodstock_Mart"),                        # door (21,21)
    ("house_wide", (10, 17), "Woodstock_House2"),                # door (12,21)
    ("lab", (28, 7), "Woodstock_Lab"),                           # door (32,11), mat (32,12)
    ("house_small_wide", (6, 10), "Woodstock_House1"),           # door (8,13) on King St
    ("house_two_storey", (15, 8), "Woodstock_House3_1F"),        # door (18,12), mat (18,13)
]
FOOT, STUBS = set(), set()
for name, (x, y), room in BUILDINGS:
    st = cat[name]
    dx, fy = sk.place(p, name, x, y, room)
    FOOT |= st.footprint(x, y)
    fy += 1
    while (dx, fy) in FOOT:                       # past a doormat
        fy += 1
    while (dx, fy) not in STREETS:                # a path from the door down to the street
        STUBS.add((dx, fy))
        fy += 1
PATHS = (STREETS | STUBS) - FOOT

# --- open ground: where the town is; everything else on land is woods -------------------------
DOWNTOWN = ls.rect(3, 8, 34, 26) | ls.rect(27, 4, 37, 13) | ls.rect(22, 3, 29, 8)
RIVERSIDE = ls.rect(32, 13, 36, 22) | ls.rect(35, 3, 40, 13)      # the green, the station's bank
SOUTH_BANK = ls.rect(0, 28, 34, H - 1)
OPEN = DOWNTOWN | RIVERSIDE | SOUTH_BANK | PATHS | ls.around(BRIDGE, 1)
# soft woods edges, stepped (landscape.forest_edge): north of town, the west, south of the road
OPEN -= ls.forest_edge(0, 0, 23, 9, "S", amp=3, seed=151)
OPEN -= ls.forest_edge(0, 8, 9, 27, "E", amp=4, seed=152)
OPEN -= ls.forest_edge(30, 0, 40, 5, "S", amp=2, seed=153) - ls.rect(35, 3, 40, 5)
OPEN -= ls.forest_edge(0, 39, 24, H - 1, "N", amp=2, seed=154)
# groves inside the town: on the creek's north bank behind Water Street, beside the two-storey
# house, and two on the south bank between the creek and the highway
GROVES = (ls.blob(16.5, 25.5, 3.5, 1.4, seed=156) | ls.rect(21, 8, 22, 11)
          | ls.blob(10, 34, 3.2, 1.3, seed=157) | ls.blob(30.5, 33.5, 2.2, 1.3, seed=158))
OPEN -= GROVES
# south-east of the junction: woods down to the river, so the seam with Route 202 (whose river
# is still the prototype's, narrower, until M17 rebuilds it) stays out of reach and out of view
OPEN -= ls.rect(27, 36, 35, H - 1)
OPEN |= PATHS | ls.around(BRIDGE, 1)

for (x, y) in WATER - ROCKS:
    sk.set(x, y, "~")
for (x, y) in ROCKS:
    sk.set(x, y, "r")
for (x, y) in BRIDGE:
    sk.set(x, y, "H")
for (x, y) in PATHS:
    sk.set(x, y, "=")

RING = ls.around(FOOT, 1) - FOOT
CLEAR = ls.around(PATHS, 1) | RING | FOOT | ls.around(WATER, 1) | ls.around(BRIDGE, 1)
land = ls.rect(0, 0, W - 1, H - 1) - WATER
woods = land - OPEN - CLEAR
# Two tree grids: most woods stand on even rows; where a street's margin and the creek's leave
# an odd pair of rows (behind Water Street, the south bank, south of the highway, whose margin
# takes row 38), the trees stand on odd rows. The areas don't overlap (plant clears its own).
ODD = ls.rect(11, 23, 22, 27) | ls.rect(5, 32, 16, 35) | ls.rect(0, 38, 24, H - 1)
ls.plant(sk, woods, ls.rect(0, 0, W - 1, H - 1) - ODD, keep_clear=CLEAR)
ls.plant(sk, woods, ODD, parity=(0, 1), keep_clear=CLEAR)
# the odd grid's last band runs off the map: the bottom row south of the highway is the tops of
# trees cut by the border (as vanilla's edges are), not a strip of grass along the edge
# (never under a sapling, whose trunk keeps open ground below it; whole trees only)
run = []
for x in range(0, 25):
    if x < 24 and sk.get(x, H - 2) != "y":
        run.append(x)
        continue
    for cx in run[:len(run) - len(run) % 2]:
        sk.set(cx, H - 1, "T")
    run = []

# --- gardens, the green, accents -------------------------------------------------------------
GARDEN = [((4, 11), 4), ((12, 11), 3), ((11, 9), 3), ((6, 16), 3)]   # the community garden
GREEN = [((34, 16), 4), ((33, 19), 3), ((35, 10), 3), ((36, 6), 3)]   # the riverside green, the bank
TOWN = [((27, 23), 2), ((19, 23), 2), ((23, 18), 2), ((14, 16), 2), ((28, 5), 3), ((23, 25), 2)]
BANKS = [((4, 30), 3), ((15, 34), 3), ((21, 32), 3), ((29, 31), 3), ((6, 39), 2), ((18, 38), 3)]
for i, ((x, y), n) in enumerate(GARDEN + GREEN + TOWN + BANKS):
    ls.flower_bed(sk, x, y, n, seed=160 + i, keep_clear=CLEAR - RING)
ls.nestle(sk, land, 4, seed=171, min_gap=9, keep_clear=CLEAR)

# --- sign posts (their text: design/maps/Woodstock_2.events.toml) ----------------------------
SIGNS = {
    "TownSign": (24, 34),       # beside Main Street at the junction, seen from both roads
    "CreekSign": (27, 31),      # at the bridge's south end: the Meduxnekeag
    "StationSign": (30, 13),    # beside the path to the station's door
    "GardenSign": (5, 12),      # in the community garden
    "NorthSign": (24, 5),       # where Main Street ends: the trail to Hartland is closed
}
for name, (x, y) in SIGNS.items():
    sk.set(x, y, "s")

out = os.path.join(HERE, "Woodstock_2.txt")
sk.save(out)
print("wrote", out)
for r in sk.rows:
    print("".join(r))
