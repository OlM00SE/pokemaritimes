"""CliffLab: dev test map for cliffs and terraces (milestone 17). Writes design/maps/CliffLab.txt.

Run:  python design/maps/clifflab_design.py
      python dev/mapgen.py build design/maps/CliffLab.txt --fresh [--apply]

A valley meadow under a wooded upland (not linked into the world; tests warp in) that uses every
cliff piece (mapkit/cliffs.py) and every way between levels:
  - the upland (level 1): an L-shaped terrace running off the north edge, its south face two
    rows tall, with the inside corners where the face turns down the lobe (089/074 under the
    face's top row, 0BE/0BF where the rims meet) and 2-wide stairs up the face
  - a knoll on it (level 2): a one-row face with 1-wide stairs
  - a road climbing through a cutting in the upland's east flank (a graded road)
  - a bench (level 1) in the meadow: stairs up, and a ledge in its face to hop back down
  - a pond under the upland, a tile of grass at the cliff's foot
  - a free-standing rock (level 1, no way up, two trees on top): every side of a plateau,
    convex corners
Spawn (the map's only "entrance"): (4,27).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.sketch import Sketch
from mapkit import landscape as ls

W, H = 40, 32
sk = Sketch("CliffLab", ["." * W for _ in range(H)], [
    "// CliffLab - cliffs and terraces (generated by design/maps/clifflab_design.py)",
    "// legend: . grass  , tall grass  = path  o pond  T forest  ^ cliff  % stairs  v ledge  # keep"])

# --- levels and walls (low terraces first) -----------------------------------------------------
UPLAND = ls.rect(0, 0, 31, 11) | ls.rect(0, 12, 11, 19)          # the L: the lobe runs south on the west
ls.terrace(sk, UPLAND, 1, face=2)
KNOLL = ls.rect(15, 3, 25, 7)
ls.terrace(sk, KNOLL, 2, face=1)
BENCH = ls.rect(24, 16, 35, 21)
ls.terrace(sk, BENCH, 1, face=1)
ROCK = ls.rect(16, 23, 21, 26)
ls.terrace(sk, ROCK, 1, face=1)

# --- ways between levels --------------------------------------------------------------------------
ls.stairs(sk, 19, 10, width=2)                    # the upland's face (rows 10-11)
ls.stairs(sk, 20, 7, width=1)                     # the knoll's face (row 7)
ls.stairs(sk, 32, 21, width=2)                    # the bench's face (row 21)
for x in range(27, 31):                           # a ledge in the bench's face: hop down
    sk.set(x, 21, "v")
# the road: in from the east edge, west through a cutting in the upland's east flank (x 31)
ROAD = ls.rect(31, 5, W - 1, 6)
ls.cutting(sk, ls.rect(31, 5, 31, 6), 0)
for x, y in ROAD:
    sk.set(x, y, "=")
UP_ROAD = ls.rect(26, 5, 30, 6)                   # on the upland, to the knoll's foot
for x, y in UP_ROAD:
    sk.set(x, y, "=")

# --- water, forest, meadow ------------------------------------------------------------------------
POND = ls.rect(14, 14, 19, 16) | ls.rect(15, 17, 18, 17)
for x, y in POND:
    sk.set(x, y, "o")
CLEAR = (ls.around(POND, 1) | ls.around(ROAD | UP_ROAD, 1) | ls.cliff_clearance(sk)
         | ls.ledge_clearance(sk) | ls.rect(2, 26, 6, 29))
ALL = ls.rect(0, 0, W - 1, H - 1)
woods = (ls.rect(0, 0, 13, 1) | ls.rect(0, 2, 1, 17) | ls.rect(0, 28, W - 1, H - 1)
         | ls.rect(36, 8, W - 1, 27) | ls.rect(0, 20, 1, 27))
ls.plant(sk, woods, ALL, keep_clear=CLEAR)
sk.fill(17, 24, 20, 25, "T")                      # two trees on the rock: nobody can climb it
ls.meadow(sk, ls.blob(8, 24, 4, 1.6, seed=1701), seed=1702, tufts=2, keep_clear=CLEAR)
ls.meadow(sk, ls.blob(5, 6, 2.5, 1.5, seed=1703), seed=1704, tufts=1, keep_clear=CLEAR)

out = os.path.join(HERE, "CliffLab.txt")
sk.save(out)
print("wrote", out)
for y, r in enumerate(sk.rows):
    print("".join(r), "".join(str(v) for v in sk.levels[y]))
