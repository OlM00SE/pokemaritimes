"""Route 202: the river road to the Meductic bend (milestone 17). Writes design/maps/Route202_1.txt.

Run:  python design/maps/route202_design.py
      python dev/mapgen.py build design/maps/Route202_1.txt --fresh [--apply]

Built from the corridor plan's underlay (design/region/corridor.toml: 42x36 at 0.5 km a tile;
`dev/corridor.py underlay "Route 202"`): the Saint John from real data, entering from Woodstock
at the top (columns 21-27) and swinging east at the Meductic bend (it leaves the east edge on
rows 10-17); the road's seams at Woodstock (columns 9-10) and the east edge (rows 25-26).

The real valley below Woodstock is a trench in the upland: wooded valley walls, river terraces
stepping down to the intervale flats, brooks cutting ravines through the terraces to the river.
Three levels (mapkit/cliffs.py), the camera looking north:
  * level 0, the flats: Woodstock's outskirts at the top, the riverside meadow, the brook's
    ravine floor, and the Meductic intervale inside the bend (hay fields);
  * level 1, the terrace the road runs on, its rims looking down on the flats;
  * level 2, the wooded upland in the south-west, and the far bank: its bluffs rise straight
    from a strip of shore, two-row faces looking back at the road across the river.
The brook comes out of the upland in the west and runs east through its ravine to the river:
the ravine's north wall is a two-row face. The road drops through cuttings to cross the brook
on a plank bridge, then climbs back onto the terrace, runs south-east and turns east along the
south bank at the bend. Stairs climb from the brook to the north terrace; from that terrace a
ledge drops to the riverside meadow; a farm lane goes down a cutting to the intervale; a logging
trail climbs into the upland, where a clearing hides an item. An island in the river (Surf, later).
Seams: Woodstock_2 above (the plan's offset 16; its south edge is level 0 like ours), the
Fredericton prototype on the east (an interim join until Nackawic, M18).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.sketch import Sketch
from mapkit.geo import Plan
from mapkit import landscape as ls

W, H = 42, 36
under = Plan().underlay("Route 202")
assert (len(under[0]), len(under)) == (W, H), "the plan's size changed"
sk = Sketch("Route202_1", ["." * W for _ in range(H)], [
    "// Route 202 - the river road to the Meductic bend (generated by design/maps/route202_design.py)",
    "// legend: . grass  , tall grass  = path  : sand  ~ river  T forest  * flowers  b boulder  y sapling",
    "//         s sign  H bridge  ^ cliff  % stairs  v > ledges  # keep;  // level: terrace levels 0-2"])
ALL = ls.rect(0, 0, W - 1, H - 1)


def polygon(pts):
    """Cells whose centres lie inside the polygon (map coordinates, vertices in order)."""
    out = set()
    for y in range(H):
        for x in range(W):
            px, py, inside = x + 0.5, y + 0.5, False
            for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
                if (y0 > py) != (y1 > py) and px < x0 + (py - y0) * (x1 - x0) / (y1 - y0):
                    inside = not inside
            if inside:
                out.add((x, y))
    return out


# --- the river (real data) -----------------------------------------------------------------------
RIVER = {(x, y) for y in range(H) for x in range(W) if under[y][x] == "~"}
dist_river = lambda x, y: min(max(abs(x - rx), abs(y - ry)) for rx, ry in RIVER)
ISLAND = ls.rect(31, 9, 34, 11)                   # mid-river below the riverside meadow
RIVER -= ISLAND
# (the river's column 27 meets a tile of Woodstock's bank on row 0: as land it would open a way from
# the town down the far bank's shore, around the whole route)

# --- levels and walls (low terraces first) ---------------------------------------------------------
BROOK_FLOOR = ls.rect(0, 12, 30, 15)               # the ravine floor: the brook (13-14) and its banks
NORTH_TERRACE = ls.rect(0, 4, 16, 11)              # rim on row 4; the ravine's face on rows 10-11
# the scarps step in runs of several tiles (bays and spurs), as vanilla's edges do: a staircase of
# single steps reads as a jagged line when all the camera sees is a rim
SOUTH_TERRACE = ls.rect(0, 16, 16, H - 1) | ls.rect(17, 18, 21, H - 1) | ls.rect(22, 20, W - 1, H - 1)
UPLAND = (ls.rect(0, 19, 4, H - 1) | ls.rect(5, 23, 10, H - 1) | ls.rect(10, 27, 18, H - 1)
          | ls.rect(19, 28, W - 1, H - 1))
# the far bank steps down the river in blocks, each with a two-row face and a flank: a staircase
# of single steps would put inside corners beside face tops (089 by 07C), which vanilla never
# does. It starts east of Woodstock's last column (31), so no wall meets the town's trees; the
# strip of shore between it and the water stays (Surf, later)
FAR_BANK = ls.rect(32, 0, W - 1, 2) | ls.rect(35, 3, W - 1, 5) | ls.rect(38, 6, W - 1, 7)
assert all(dist_river(x, y) >= 2 for x, y in FAR_BANK), "a far-bank wall would touch the river"
ls.terrace(sk, NORTH_TERRACE, 1, face=2)
ls.terrace(sk, SOUTH_TERRACE - BROOK_FLOOR, 1, face=1)
ls.terrace(sk, UPLAND, 2, face=1)
ls.terrace(sk, FAR_BANK, 2, face=2)

# --- water ------------------------------------------------------------------------------------------
BROOK = ls.rect(0, 13, 30, 14)
for x, y in RIVER | BROOK:
    sk.set(x, y, "~")
BRIDGE = ls.rect(11, 13, 12, 14)
for x, y in BRIDGE:
    sk.set(x, y, "H")

# --- the road: straight runs, two tiles wide ------------------------------------------------------
ROAD = ls.rect(9, 0, 10, 3)                        # out of Woodstock, on the flats
ROAD |= ls.rect(9, 5, 10, 6) | ls.rect(9, 7, 12, 8) | ls.rect(11, 9, 12, 9)   # on the north terrace
ROAD |= ls.rect(11, 17, 12, 21)                    # up out of the ravine
ROAD |= ls.rect(11, 22, 31, 23)                    # east along the terrace
ROAD |= ls.rect(30, 24, 34, 24) | ls.rect(33, 25, W - 1, 26) | ls.rect(30, 23, 34, 23)
ROAD |= ls.rect(33, 24, 34, 24)
CUT_N = ls.rect(9, 4, 10, 4)                       # through the north terrace's rim
CUT_RAVINE_N = ls.rect(11, 10, 12, 11)             # down the ravine's face
CUT_RAVINE_S = ls.rect(11, 16, 12, 16)             # up through the south terrace's rim
for cells in (CUT_N, CUT_RAVINE_N, CUT_RAVINE_S):
    ls.cutting(sk, cells, 0)
for x, y in ROAD:
    sk.set(x, y, "=")


def climb(path, low, high):
    """A path through a rim: its wall cells become a cutting at the lower level; the path's
    cells beyond the rim (north of it) stay low, the rest high."""
    cut = {(x, y) for x, y in path if sk.get(x, y) == "^"}
    rim = min(y for _, y in cut)
    ls.cutting(sk, cut, low)
    sk.set_level({(x, y) for x, y in path if y < rim}, low)
    sk.set_level({(x, y) for x, y in path if y > rim}, high)
    for x, y in path:
        sk.set(x, y, "=")


LANE = ls.rect(26, 18, 27, 21)                     # the farm lane: down to the intervale (rim row 20)
climb(LANE, 0, 1)
TRAIL = ls.rect(37, 27, 38, 31)                    # the logging trail: up into the upland (rim row 28)
climb(TRAIL, 1, 2)

# --- stairs and ledges --------------------------------------------------------------------------------
ls.stairs(sk, 4, 10, width=2)                      # from the brook up to the north terrace
for y in range(6, 9):                              # the terrace's east flank: hop down to the meadow
    sk.set(16, y, ">")

# --- open ground, forest -------------------------------------------------------------------------------
WALLS = ls.cells_of(sk, "^%")
CLEAR = (ls.around(ROAD | LANE | TRAIL, 1) | ls.around(BRIDGE, 1) | ls.cliff_clearance(sk)
         | ls.ledge_clearance(sk) | ls.around(RIVER | BROOK, 1) | ISLAND)
UPLAND_CLEARING = ls.blob(37, 32.5, 3.2, 1.8, seed=2201, wobble=0.25) & UPLAND
# forest: the upland right up to its crest (the rim reads as the wooded slope's edge), the far
# bank's top, the outskirts' woods at the top (Woodstock's continue), the north terrace's west
# half, and groves on the south terrace between the road and the upland
WOODS = ((UPLAND - UPLAND_CLEARING) | FAR_BANK
         | ls.rect(0, 2, 7, 3) | ls.rect(12, 0, 15, 3)
         | ls.rect(0, 5, 3, 9) | ls.rect(8, 5, 8, 9) | ls.rect(13, 5, 15, 9)
         | ls.rect(0, 17, 9, 21) | ls.forest_edge(13, 24, 36, 27, "N", amp=2, seed=2206)
         | ls.rect(19, 5, 22, 6) | ls.rect(36, 18, 41, 19)
         | ls.rect(40, 8, 41, 9))                     # the far shore stops short of the east edge
ls.plant(sk, WOODS - CLEAR - WALLS, ALL, keep_clear=CLEAR)
# Woodstock's bottom row holds tree tops at columns 0 and 3-6 (its 16 and 19-22): their lower
# halves stand on row 0 (trees cut by the top border; row 1 stays open so they can't pair down)
for x in (0, 3, 4, 5, 6):
    sk.set(x, 0, "T")
for x in range(0, 9):
    assert sk.get(x, 1) != "T", f"row 1 at {x} must stay open under the seam's tree bottoms"
# hay fields on the intervale, tall grass in the meadow, the glade and under the upland
ls.meadow(sk, ls.rect(19, 16, 24, 17) | ls.rect(29, 16, 34, 18), seed=2211, tufts=3, keep_clear=CLEAR)
ls.meadow(sk, ls.blob(18, 3, 2, 2.4, seed=2212), seed=2213, tufts=2, keep_clear=CLEAR)
ls.meadow(sk, ls.blob(6, 7, 2, 1, seed=2214), seed=2215, tufts=1, keep_clear=CLEAR)
for i, ((x, y), n) in enumerate([((33, 10), 2), ((24, 19), 2), ((36, 33), 3), ((7, 15), 2)]):
    ls.flower_bed(sk, x, y, n, seed=2230 + i, keep_clear=CLEAR - ISLAND)

# --- signs (their text: design/maps/Route202_1.events.toml) ------------------------------------------
# the route sign by the road out of Woodstock; Meductic's by the farm lane at the bend
for SIGN in ((8, 2), (28, 21)):
    assert sk.get(*SIGN) in ".T", f"the sign's spot {SIGN} is {sk.get(*SIGN)!r}"
    sk.set(*SIGN, "s")

out = os.path.join(HERE, "Route202_1.txt")
sk.save(out)
print("wrote", out)
for y, r in enumerate(sk.rows):
    print(f"{y:2} {''.join(r)}  {''.join(str(v) for v in sk.levels[y])}")
