"""LedgeLab: dev test map for the ledge vocabulary. Writes design/maps/LedgeLab.txt.

Run:  python design/maps/ledgelab_design.py
      python dev/mapgen.py build design/maps/LedgeLab.txt --fresh [--apply]

A terraced meadow (not linked into the world; tests warp in) that uses every ledge piece:
  - a central mesa: west and east columns with top caps, closed by the two convex corners
    (08D, 08E) and a south row; a pond on top
  - side wings: a row turning down into a column (06F over '<', 06E over '>'), with free
    column bottoms (106, 107)
  - stair steps down to the east (06F over 08D) and down to the west (06E over 08E)
  - a free-standing row with both end caps, landing in tall grass
  - row ends against the forest edge (capped)
A dirt path climbs back from the bottom to the top, so no ledge is a trap; the checker's
trap test proves it. Spawn (the map's only "entrance"): (11,3).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "dev"))
from mapkit.sketch import Sketch

W, H = 32, 28
sk = Sketch("LedgeLab", ["." * W for _ in range(H)], [
    "// LedgeLab - dev map for ledges (generated by design/maps/ledgelab_design.py)",
    "// legend: . grass  , tall grass  = path  : sand  ~ river  o pond  T forest  # keep",
    "//         v ledge (jump south)  < ledge (jump west)  > ledge (jump east)"])
f = sk.fill


def row(y, x0, x1):          # a south-facing ledge row
    f(x0, y, x1, y, "v")


def col(x, y0, y1, ch):      # a west ('<') or east ('>') ledge column
    f(x, y0, x, y1, ch)


# --- forest frame (2 thick, so whole 2x2 trees) ---
f(0, 0, W - 1, 1, "T"); f(0, H - 2, W - 1, H - 1, "T")
f(0, 0, 1, H - 1, "T"); f(W - 2, 0, W - 1, H - 1, "T")

# --- top meadow (y 2-6): the high ground ---
f(3, 3, 6, 4, ",")
f(24, 3, 27, 4, ",")
f(16, 3, 17, 4, "T")                 # a lone tree

# --- side wings: a row turning down into a column ---
row(7, 2, 6); col(6, 8, 10, "<")     # 0D5 087.. 06F / 085 085 106
row(7, 25, 29); col(25, 8, 10, ">")  # 06E 087.. 0D6 / 086 086 107

# --- central mesa ---
col(9, 9, 12, "<"); col(22, 9, 12, ">")   # 0FE 085.. / 0FF 086..
row(13, 9, 22)                            # 08D 087... 08E
f(14, 9, 17, 10, "o")                     # pond on top
f(11, 11, 13, 12, ","); f(18, 11, 20, 12, ",")

# --- lower terraces: stair steps ---
row(17, 3, 8); row(18, 8, 13)        # step down east: 0D5 087.. 06F / 08D 087.. 0D6
row(17, 23, 28); row(18, 18, 23)     # step down west: 06E 087.. 0D6 / 0D5 087.. 08E

# --- a free-standing row, landing in tall grass ---
row(21, 19, 26)
f(18, 22, 27, 24, ",")
f(3, 20, 6, 23, ",")

# --- the way back up: a dirt path from the bottom meadow to the top ---
f(15, 15, 16, 25, "=")               # down through the gap between the two stair steps
f(7, 15, 16, 16, "=")                # west under the mesa
f(7, 5, 8, 16, "=")                  # north between the wing and the mesa
f(7, 5, 12, 6, "=")                  # out onto the top meadow

# --- a few trees for shape ---
f(28, 12, 29, 15, "T")
f(2, 12, 3, 13, "T")
f(11, 23, 12, 24, "T")

out = os.path.join(HERE, "LedgeLab.txt")
sk.save(out)
print("wrote", out)
